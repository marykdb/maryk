private object EncryptedFloatingModel : RootDataModel<EncryptedFloatingModel>() {
    val value by number(1u, type = Float64, sensitive = true, unique = true)
}

private object MixedEncryptedModel : RootDataModel<MixedEncryptedModel>() {
    val value by number(1u, type = Float64)
    val label by string(2u, sensitive = true, unique = true)
}

class FloatingPointStorageMigrationTest {
    private class Metadata : StorageFormatUpgradeStore {
        override val namespaceCount = 0
        override val identity = "encrypted-float"
        private val values = mutableMapOf<String, ByteArray>()
        override suspend fun get(namespace: Int, key: ByteArray) = values[key.toHexString()]
        override suspend fun scan(namespace: Int, after: ByteArray?, limit: UInt): List<StorageFormatRow> = emptyList()
        override suspend fun convert(namespace: Int, row: StorageFormatRow) = row
        override suspend fun commit(writes: List<StorageFormatWrite>) {
            writes.forEach { if (it.value == null) values.remove(it.key.toHexString()) else values[it.key.toHexString()] = it.value }
        }
    }

    @Test
    fun released013GoldenCellsAndUniqueClaimsPreserveEveryFloatingBit() = runTest {
        // Generated by compiling and running the unchanged Float/Double/Int/Long/Byte
        // writers from release 0.13.0 (1113a4851ab8b2c9bfa86756b6f07aa4a3327dbc).
        // Keep these literal: an inverse of today's writer would hide codec drift.
        val doubles = listOf(
            Triple("fff8000000000002", "8007fffffffffffe", "0007fffffffffffd"),
            Triple("fff0000000000000", "8010000000000000", "000fffffffffffff"),
            Triple("bff0000000000000", "c010000000000000", "400fffffffffffff"),
            Triple("8000000000000000", "0000000000000000", "7fffffffffffffff"),
            Triple("0000000000000000", "0000000000000001", "8000000000000000"),
            Triple("0000000000000001", "0000000000000002", "8000000000000001"),
            Triple("3ff0000000000000", "3ff0000000000001", "bff0000000000000"),
            Triple("7ff0000000000000", "7ff0000000000001", "fff0000000000000"),
            Triple("7ff8000000000001", "7ff8000000000002", "fff8000000000001"),
            Triple("7ff8000000000002", "7ff8000000000003", "fff8000000000002"),
        )
        val floats = listOf(
            Triple("ffc00002", "803ffffe", "003ffffd"),
            Triple("ff800000", "80800000", "007fffff"),
            Triple("bf800000", "c0800000", "407fffff"),
            Triple("80000000", "00000000", "7fffffff"),
            Triple("00000000", "00000001", "80000000"),
            Triple("00000001", "00000002", "80000001"),
            Triple("3f800000", "3f800001", "bf800000"),
            Triple("7f800000", "7f800001", "ff800000"),
            Triple("7fc00001", "7fc00002", "ffc00001"),
            Triple("7fc00002", "7fc00003", "ffc00002"),
        )
        val migration = FloatingPointStorageMigration(1u, ReleasedFloatingModel, Metadata(), null)
        for ((bits, released, current) in doubles) {
            val qualifier = ReleasedFloatingModel.double.ref().toStorageByteArray()
            val encoded = migration.convertCell(ByteArray(16), qualifier, byteArrayOf(1) + released.hexToByteArray()).value
            assertContentEquals(byteArrayOf(1) + current.hexToByteArray(), encoded)
            var offset = 1
            val decoded = NumberDefinition(type = Float64).readStorageBytes(8) { encoded[offset++] }
            val sourceBits = bits.toULong(16).toLong()
            assertEquals(Double.fromBits(sourceBits).toBits(), decoded.toBits())
            if (supportsRawNaNPayloads) assertEquals(sourceBits, decoded.toRawBits())
            assertContentEquals(qualifier + encoded, migration.convertUnique(qualifier + byteArrayOf(1) + released.hexToByteArray()))
        }
        for ((bits, released, current) in floats) {
            val qualifier = ReleasedFloatingModel.float.ref().toStorageByteArray()
            val encoded = migration.convertCell(ByteArray(16), qualifier, byteArrayOf(1) + released.hexToByteArray()).value
            assertContentEquals(byteArrayOf(1) + current.hexToByteArray(), encoded)
            var offset = 1
            val decoded = NumberDefinition(type = Float32).readStorageBytes(4) { encoded[offset++] }
            val sourceBits = bits.toUInt(16).toInt()
            assertEquals(Float.fromBits(sourceBits).toBits(), decoded.toBits())
            if (supportsRawNaNPayloads) assertEquals(sourceBits, decoded.toRawBits())
            assertContentEquals(qualifier + encoded, migration.convertUnique(qualifier + byteArrayOf(1) + released.hexToByteArray()))
        }
    }

    @Test
    fun leavesUnaffectedCiphertextAndSensitiveUniqueTokensUntouchedWithoutAProvider() = runTest {
        val provider = AesGcmHmacSha256EncryptionProvider(ByteArray(32) { it.toByte() }, ByteArray(32) { (it + 32).toByte() })
        val record = ByteArray(16)
        val qualifier = MixedEncryptedModel.label.ref().toStorageByteArray()
        val plain = byteArrayOf(1) + StringDefinition().toStorageBytes("unchanged")
        val encrypted = FieldEncryptionEnvelope.Contextual.magic + provider.encrypt(FieldEncryptionContext(1u, record, qualifier), plain)
        val unique = qualifier + provider.deriveDeterministicToken(1u, qualifier, plain)
        val migration = FloatingPointStorageMigration(1u, MixedEncryptedModel, Metadata(), null)
        val converted = migration.convertCell(record, qualifier, encrypted)
        assertContentEquals(qualifier, converted.key)
        assertContentEquals(encrypted, converted.value)
        assertContentEquals(unique, migration.convertUnique(unique))
    }

    @Test
    fun convertsContextualCiphertextAndPersistsUniqueTokenTranslationForRestart() = runTest {
        val metadata = Metadata()
        val provider = AesGcmHmacSha256EncryptionProvider(ByteArray(32) { it.toByte() }, ByteArray(32) { (it + 32).toByte() })
        val record = ByteArray(16) { it.toByte() }
        val qualifier = EncryptedFloatingModel.value.ref().toStorageByteArray()
        val context = FieldEncryptionContext(1u, record, qualifier)
        val legacy = byteArrayOf(1) + legacyFloatBytes(-1.0)
        val current = byteArrayOf(1) + NumberDefinition(type = Float64).toStorageBytes(-1.0)
        val encrypted = FieldEncryptionEnvelope.Contextual.magic + provider.encrypt(context, legacy)
        val oldUnique = qualifier + provider.deriveDeterministicToken(1u, qualifier, legacy)
        val expectedUnique = qualifier + provider.deriveDeterministicToken(1u, qualifier, current)
        val migration = FloatingPointStorageMigration(1u, EncryptedFloatingModel, metadata, provider)
        val converted = migration.convertCell(record, qualifier, encrypted)
        assertContentEquals(qualifier, converted.key)
        assertContentEquals(current, provider.decrypt(context, converted.value, 4, converted.value.size - 4))
        // Recreate the converter, as after a checkpoint/reopen; the mapping is durable.
        val resumed = FloatingPointStorageMigration(1u, EncryptedFloatingModel, metadata, provider)
        assertContentEquals(expectedUnique, resumed.convertUnique(oldUnique))
    }

    @Test
    fun retainedAndActiveTokenCandidatesMigrateIndependentlyAcrossHistoricValues() = runTest {
        val previous = AesGcmHmacSha256EncryptionProvider(ByteArray(32) { it.toByte() }, ByteArray(32) { (it + 32).toByte() })
        val active = AesGcmHmacSha256EncryptionProvider(ByteArray(32) { (it + 64).toByte() }, ByteArray(32) { (it + 96).toByte() })
        val keyring = KeyringFieldEncryptionProvider("active", mapOf("previous" to previous, "active" to active), legacyProvider = previous)
        val metadata = Metadata()
        val qualifier = EncryptedFloatingModel.value.ref().toStorageByteArray()
        val contexts = listOf(ByteArray(16), ByteArray(16) { 1 }).map { FieldEncryptionContext(1u, it, qualifier) }
        val expectedClaims = mutableListOf<Pair<ByteArray, ByteArray>>()
        for ((context, value) in contexts.zip(listOf(-0.0, Double.fromBits(0x7ff8000000000001L)))) {
            val legacy = byteArrayOf(1) + legacyFloatBytes(value)
            val current = byteArrayOf(1) + NumberDefinition(type = Float64).toStorageBytes(value)
            val encrypted = FieldEncryptionEnvelope.Contextual.magic + previous.encrypt(context, legacy)
            val migration = FloatingPointStorageMigration(1u, EncryptedFloatingModel, metadata, keyring)
            val converted = migration.convertCell(context.recordKey, qualifier, encrypted)
            assertContentEquals(current, keyring.decrypt(context, converted.value, 4, converted.value.size - 4))
            val oldTokens = keyring.deriveDeterministicTokenCandidates(1u, qualifier, legacy)
            val currentTokens = keyring.deriveDeterministicTokenCandidates(1u, qualifier, current)
            assertEquals(2, oldTokens.size)
            expectedClaims += oldTokens.zip(currentTokens).map { qualifier + it.first to qualifier + it.second }
        }
        // A fresh converter must recover translations for every retained version and token key.
        val resumed = FloatingPointStorageMigration(1u, EncryptedFloatingModel, metadata, keyring)
        for ((old, current) in expectedClaims) assertContentEquals(current, resumed.convertUnique(old))
    }

    @Test
    fun conversionPreservesDistinctNanPayloadsAndDeletionMarkers() = runTest {
        val migration = FloatingPointStorageMigration(1u, EncryptedFloatingModel, Metadata(), null)
        val qualifier = EncryptedFloatingModel.value.ref().toStorageByteArray()
        val nan = Double.fromBits(0x7ff8000000000001L)
        // Use an ordinary model for the plaintext payload case.
        assertContentEquals(byteArrayOf(0), migration.convertCell(ByteArray(16), qualifier, byteArrayOf(0)).value)
        val ordinary = FloatingPointStorageMigration(1u, PlainFloatingModel, Metadata(), null)
        val converted = ordinary.convertCell(ByteArray(16), qualifier, byteArrayOf(1) + legacyFloatBytes(nan))
        var offset = 1
        assertEquals(nan.toRawBits(), NumberDefinition(type = Float64).readStorageBytes(8) { converted.value[offset++] }.toRawBits())
    }
}

private object PlainFloatingModel : RootDataModel<PlainFloatingModel>() {
    val value by number(1u, type = Float64)
}

private object ReleasedFloatingModel : RootDataModel<ReleasedFloatingModel>() {
    val double by number(1u, type = Float64, unique = true)
    val float by number(2u, type = Float32, unique = true)
}
